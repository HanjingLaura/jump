const Sprite &spriteGet(SpriteId id) {
  return kSprites[id];
}

void drawSprite(Adafruit_GFX &g, int16_t x, int16_t y, SpriteId id) {
  const Sprite &s = kSprites[id];
  g.drawBitmap(x, y, s.data, s.w, s.h, SSD1306_WHITE);
}

