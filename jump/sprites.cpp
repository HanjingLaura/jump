static const Sprite kSprites[] = {
  {spr_run1, 16, 16},
  {spr_run2, 16, 16},
  {spr_jump, 16, 16},
  {obs_post, 8, 14},
};

const Sprite &spriteGet(SpriteId id) {
  return kSprites[id];
}

void drawSprite(Adafruit_GFX &g, int16_t x, int16_t y, SpriteId id) {
  const Sprite &s = kSprites[id];
  g.drawBitmap(x, y, s.data, s.w, s.h, SSD1306_WHITE);
}

void drawBitmapProgmem(Adafruit_GFX &g, int16_t x, int16_t y,
                       const uint8_t *bmp, uint8_t w, uint8_t h) {
  g.drawBitmap(x, y, bmp, w, h, SSD1306_WHITE);
}
